        // Animate statistics counter
        function animateStats() {
            const statElements = document.querySelectorAll('.stat-number');
            statElements.forEach(el => {
                const target = parseInt(el.getAttribute('data-count'));
                const duration = 2000;
                const step = target / (duration / 16);
                let current = 0;
                const startTime = Date.now();
                
                const timer = setInterval(() => {
                    current += step;
                    const elapsed = Date.now() - startTime;
                    
                    if (current >= target || elapsed >= duration) {
                        current = target;
                        el.textContent = target.toLocaleString();
                        clearInterval(timer);
                    } else {
                        el.textContent = Math.floor(current).toLocaleString();
                    }
                }, 16);
            });
        }
        
        // Initialize stats animation when in view
        const impactCounter = document.querySelector('.impact-counter');
        if (impactCounter) {
            const observerOptions = {
                threshold: 0.2,
                rootMargin: '0px 0px -100px 0px'
            };
            
            const observer = new IntersectionObserver((entries) => {
                entries.forEach(entry => {
                    if (entry.isIntersecting) {
                        if (entry.target.classList.contains('impact-counter')) {
                            animateStats();
                        }
                        observer.unobserve(entry.target);
                    }
                });
            }, observerOptions);
            
            observer.observe(impactCounter);
        }
        
