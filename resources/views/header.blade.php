    <script>
        // Mobile menu toggle
        const mobileMenuBtn = document.getElementById('mobileMenuBtn');
        const mobileCloseBtn = document.getElementById('mobileCloseBtn');
        const header = document.getElementById('header');
        
        // Open mobile menu
        mobileMenuBtn.addEventListener('click', () => {
            header.classList.add('mobile-menu-active');
            document.body.style.overflow = 'hidden';
        });
        
        // Close mobile menu
        mobileCloseBtn.addEventListener('click', () => {
            header.classList.remove('mobile-menu-active');
            document.body.style.overflow = '';
        });
        
        // Close mobile menu when clicking on a link
        const navLinks = document.querySelectorAll('#mainNav a');
        navLinks.forEach(link => {
            link.addEventListener('click', () => {
                header.classList.remove('mobile-menu-active');
                document.body.style.overflow = '';
                
                // Update active class
                navLinks.forEach(item => item.classList.remove('active'));
                link.classList.add('active');
            });
        });
        
        // Header scroll effect
        window.addEventListener('scroll', () => {
            if (window.scrollY > 100) {
                header.classList.add('header-scrolled');
            } else {
                header.classList.remove('header-scrolled');
            }
            
            // Update active nav based on scroll position
            updateActiveNavOnScroll();
        });
        
        // Update active nav on scroll
        function updateActiveNavOnScroll() {
            const sections = document.querySelectorAll('section');
            const scrollPos = window.scrollY + 150;
            
            sections.forEach(section => {
                const sectionTop = section.offsetTop;
                const sectionHeight = section.clientHeight;
                const sectionId = section.getAttribute('id');
                
                if (scrollPos >= sectionTop && scrollPos < sectionTop + sectionHeight) {
                    navLinks.forEach(link => {
                        link.classList.remove('active');
                        if (link.getAttribute('href') === `#${sectionId}`) {
                            link.classList.add('active');
                        }
                    });
                }
            });
        }
        
        // Login button functionality
        // const loginButtons = document.querySelectorAll('#loginBtn, #mobileLoginBtn');
        // loginButtons.forEach(btn => {
        //     btn.addEventListener('click', () => {
        //         alert('Login functionality will be implemented here. Redirecting to login page...');
        //         // In a real application, you would redirect to login page
        //         // window.location.href = 'login.html';
        //     });
        // });
        
        // Header Slider Functionality
        const headerSlider = document.getElementById('headerSlider');
        const prevBtn = document.getElementById('prevBtn');
        const nextBtn = document.getElementById('nextBtn');
        const sliderDots = document.getElementById('sliderDots');
        
        let currentSlide = 0;
        const totalSlides = document.querySelectorAll('.header-slide').length;
        
        // Create dots for slider
        function createDots() {
            sliderDots.innerHTML = '';
            
            for (let i = 0; i < totalSlides; i++) {
                const dot = document.createElement('div');
                dot.classList.add('dot');
                if (i === 0) dot.classList.add('active');
                dot.setAttribute('aria-label', `Go to slide ${i + 1}`);
                dot.addEventListener('click', () => {
                    goToSlide(i);
                });
                sliderDots.appendChild(dot);
            }
        }
        
        // Update slider position
        function updateSlider() {
            headerSlider.style.transform = `translateX(-${currentSlide * 100}%)`;
            
            // Update dots
            const dots = document.querySelectorAll('.dot');
            dots.forEach((dot, index) => {
                dot.classList.remove('active');
                if (index === currentSlide) {
                    dot.classList.add('active');
                }
            });
        }
        
        // Go to specific slide
        function goToSlide(slideIndex) {
            currentSlide = slideIndex;
            if (currentSlide < 0) currentSlide = totalSlides - 1;
            if (currentSlide >= totalSlides) currentSlide = 0;
            
            updateSlider();
            resetAutoSlide();
        }
        
        // Next slide
        function nextSlide() {
            currentSlide++;
            if (currentSlide >= totalSlides) currentSlide = 0;
            updateSlider();
            resetAutoSlide();
        }
        
        // Previous slide
        function prevSlide() {
            currentSlide--;
            if (currentSlide < 0) currentSlide = totalSlides - 1;
            updateSlider();
            resetAutoSlide();
        }
        
        // Event listeners
        prevBtn.addEventListener('click', prevSlide);
        nextBtn.addEventListener('click', nextSlide);
        
        // Initialize slider
        createDots();
        
        // Auto slide functionality
        let slideInterval;
        function startAutoSlide() {
            slideInterval = setInterval(nextSlide, 5000);
        }
        
        function resetAutoSlide() {
            clearInterval(slideInterval);
            startAutoSlide();
        }
        
        startAutoSlide();
        
        // Pause auto-slide on hover
        const sliderContainer = document.querySelector('.header-slider-container');
        sliderContainer.addEventListener('mouseenter', () => {
            clearInterval(slideInterval);
        });
        
        sliderContainer.addEventListener('mouseleave', () => {
            startAutoSlide();
        });
        
        // Keyboard navigation
        document.addEventListener('keydown', (e) => {
            if (e.key === 'ArrowLeft') {
                prevSlide();
            } else if (e.key === 'ArrowRight') {
                nextSlide();
            }
        });
        
        // Touch swipe support for mobile
        let touchStartX = 0;
        let touchEndX = 0;
        
        sliderContainer.addEventListener('touchstart', (e) => {
            touchStartX = e.changedTouches[0].screenX;
            clearInterval(slideInterval);
        });
        
        sliderContainer.addEventListener('touchend', (e) => {
            touchEndX = e.changedTouches[0].screenX;
            handleSwipe();
            startAutoSlide();
        });
        
        function handleSwipe() {
            const swipeThreshold = 50;
            
            if (touchStartX - touchEndX > swipeThreshold) {
                // Swipe left - next slide
                nextSlide();
            } else if (touchEndX - touchStartX > swipeThreshold) {
                // Swipe right - previous slide
                prevSlide();
            }
        }
        
        // Close mobile menu when clicking outside
        document.addEventListener('click', (e) => {
            const isClickInsideMenu = header.contains(e.target);
            const isMenuButton = e.target === mobileMenuBtn || mobileMenuBtn.contains(e.target);
            
            if (!isClickInsideMenu && !isMenuButton && header.classList.contains('mobile-menu-active')) {
                header.classList.remove('mobile-menu-active');
                document.body.style.overflow = '';
            }
        });
        
        // Initialize
        updateActiveNavOnScroll();
    </script>
